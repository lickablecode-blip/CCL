SELECT Task_Type = UAR_GET_CODE_DISPLAY( O.TASK_TYPE_CD )
, Task_Activity = UAR_GET_CODE_DISPLAY( O.TASK_ACTIVITY_CD )
, Task = O.TASK_DESCRIPTION
, task_type = uar_get_code_display(o.TASK_TYPE_CD)
, Task_EC = UAR_GET_CODE_DISPLAY( O.EVENT_CD )
, O.UPDT_DT_TM "@SHORTDATETIME"
, Task_UpdBy = P.NAME_FULL_FORMATTED
, Ovr_Amt = O.OVERDUE_MIN
, Ovr_Unit = EVALUATE( O.OVERDUE_UNITS,0,"None",1,"Min",2,"Hrs",3,"Days",4,"Weeks")
, Ret_Amt = O.RETAIN_TIME
, Ret_Unit = EVALUATE( O.RETAIN_UNITS,0,"None",1,"Min",2,"Hrs",3,"Days",4,"Weeks")
, Resched = O.RESCHEDULE_TIME
, Not_Cmpl = EVALUATE(O.CHART_NOT_CMPLT_IND,0,"No",1,"Yes")
, Cht_Done = EVALUATE(O.QUICK_CHART_DONE_IND ,0,"No",1,"Yes")
, Cht_NotDone = EVALUATE(O.QUICK_CHART_NOTDONE_IND,0,"No",1,"Yes")
;, Form = D.DEFINITION
;, Form_ES = D.EVENT_SET_NAME
;, Form_lvl = EVALUATE(D.FLAGS ,1,"Req",2,"Max", 3,"Req/Max")
, OT.UPDT_DT_TM "@SHORTDATETIME"
, Task_OrderBy = P1.NAME_FULL_FORMATTED
, Orderable = OC.PRIMARY_MNEMONIC
, Ord_Catlg = UAR_GET_CODE_DISPLAY( OC.CATALOG_TYPE_CD )
, Ord_Folder = UAR_GET_CODE_DISPLAY( OC.DCP_CLIN_CAT_CD )
, Ord_Activity = UAR_GET_CODE_DISPLAY( OC.ACTIVITY_TYPE_CD )
, Dup_Chk = EVALUATE(OC.DUP_CHECKING_IND,0,"No",1,"Yes")
, Ord_rev = EVALUATE(OC.ORDER_REVIEW_IND,0,"No",1,"Yes")
FROM
ORDER_TASK O
, DCP_FORMS_REF D
, DUMMYT D1
, PRSNL P
, ORDER_TASK_XREF OT
, DUMMYT D2
, PRSNL P1
, ORDER_CATALOG OC
PLAN O WHERE O.ACTIVE_IND = 1
JOIN D1 
JOIN P WHERE P.PERSON_ID = O.UPDT_ID
JOIN D WHERE D.DCP_FORMS_REF_ID = O.DCP_FORMS_REF_ID
 AND D.ACTIVE_IND = 1
JOIN D2
JOIN OT WHERE OT.REFERENCE_TASK_ID = O.REFERENCE_TASK_ID
JOIN P1 WHERE P1.PERSON_ID = OT.UPDT_ID
JOIN OC WHERE OC.CATALOG_CD = OT.CATALOG_CD
 AND OC.ACTIVE_IND = 1
;; WITH OUTERJOIN=D1 , OUTERJOIN=D2
