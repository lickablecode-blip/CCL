            BDC.CATEGORY_NAME
, BDC.CATEGORY_MEAN
, B.FILTER_DISPLAY
, FREETEXT_DESC =            (IF (B.FILTER_MEAN IN ("SMART_CE_DISPLAY_FORMAT", "SMART_ALLERGY_DISPLAY_FORMAT", "SMART_PROB_DISPLAY_IND") AND (BD.FREETEXT_DESC = "1.00")) "Grid with borders"
ELSEIF (B.FILTER_MEAN IN ("SMART_CE_DISPLAY_FORMAT", "SMART_ALLERGY_DISPLAY_FORMAT", "SMART_PROB_DISPLAY_IND") AND (BD.FREETEXT_DESC = "2.00")) "Grid without borders"
ELSEIF (B.FILTER_MEAN IN ("SMART_CE_DISPLAY_FORMAT", "SMART_ALLERGY_DISPLAY_FORMAT", "SMART_PROB_DISPLAY_IND") AND (BD.FREETEXT_DESC = "3.00")) "List horizontal"
ELSEIF (B.FILTER_MEAN IN ("SMART_CE_DISPLAY_FORMAT", "SMART_ALLERGY_DISPLAY_FORMAT", "SMART_PROB_DISPLAY_IND") AND (BD.FREETEXT_DESC = "4.00")) "List vertical"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "1.00") "Date Only"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "2.00") "Date Time"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "3.00") "Time Only"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "4.00") "No Date Time"
ELSEIF (B.FILTER_MEAN IN ("SMART_ENC_RETRIEVE_IND", "SMART_REPORT_ENC_IND") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Current Encounter"
ELSEIF (B.FILTER_MEAN IN ("SMART_ENC_RETRIEVE_IND", "SMART_REPORT_ENC_IND") AND BD.FREETEXT_DESC = "0") "All Encounters"
ELSEIF (B.FILTER_MEAN IN ("SMART_CE_SORTING") AND BD.FREETEXT_DESC = "1.00") "Alphabetical"
ELSEIF (B.FILTER_MEAN IN ("SMART_CE_SORTING") AND BD.FREETEXT_DESC = "2.00") "ESH Sequencing"
ELSEIF (B.FILTER_MEAN IN ("SMART_RESULT_RETRIEVE_IND", "SMART_REPORT_RESULT_IND") AND BD.FREETEXT_DESC = "0") "All Results"
ELSEIF (B.FILTER_MEAN IN ("SMART_RESULT_RETRIEVE_IND", "SMART_REPORT_RESULT_IND") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Most Recent"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_QUAL_OPT", "SMART_DT_DISPLAY_OPT") AND BD.FREETEXT_DESC = "1.00") "Posting Range"
ELSEIF (B.FILTER_MEAN IN ("SMART_DT_QUAL_OPT", "SMART_DT_DISPLAY_OPT") AND BD.FREETEXT_DESC = "2.00") "Clinical Range"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_DATE_OPT") AND BD.FREETEXT_DESC = "0") "NOT Case Sensitive"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_DATE_OPT") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Case Sensitive"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "1.00") "Short numeric date and time"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "2.00") "Abbreviated date and time"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_DT_TM_FORMAT") AND BD.FREETEXT_DESC = "3.00") "Long date and time"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_IN_PROGRESS_OPT") AND BD.FREETEXT_DESC = "0") "Exclude In Process"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_IN_PROGRESS_OPT") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Include In Process"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_ORDER_BY_OPT") AND BD.FREETEXT_DESC = "0") "All Users"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_ORDER_BY_OPT") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Current User"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_SIGNED_BY_OPT") AND BD.FREETEXT_DESC = "0") "Do NOT Display Signer"
ELSEIF (B.FILTER_MEAN IN ("SMART_REPORT_SIGNED_BY_OPT") AND BD.FREETEXT_DESC IN ("1", "1.00")) "Display Signer"
ELSEIF (B.FILTER_MEAN IN ("SMART_TM_RANGE_OPT") AND BD.VALUE_TYPE_FLAG = 1 AND BD.MPAGE_PARAM_VALUE = NULL) "All Encounters"
ELSEIF (B.FILTER_MEAN IN ("SMART_TM_RANGE_OPT") AND BD.VALUE_TYPE_FLAG = 1 AND BD.MPAGE_PARAM_VALUE = "*") "All Encounters - Specified Time Period"
ELSEIF (B.FILTER_MEAN IN ("SMART_TM_RANGE_OPT") AND BD.VALUE_TYPE_FLAG = 2 AND BD.MPAGE_PARAM_VALUE = NULL) "Current Encounter"
ELSEIF (B.FILTER_MEAN IN ("SMART_TM_RANGE_OPT") AND BD.VALUE_TYPE_FLAG = 2 AND BD.MPAGE_PARAM_VALUE = "*") "Current Encounter - Specified Time Period"
ELSE BD.FREETEXT_DESC
ENDIF)        
, BD.MPAGE_PARAM_VALUE
, UAR_GET_CODE_DISPLAY (BD.PARENT_ENTITY_ID)
, BD.UPDT_DT_TM "@SHORTDATETIME"
 
