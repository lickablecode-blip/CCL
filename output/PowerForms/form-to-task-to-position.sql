SELECT
	O.DCP_FORMS_REF_ID
	, O.ACTIVE_IND
	, O.TASK_DESCRIPTION
	, O.TASK_TYPE_CD
	, O_TASK_TYPE_DISP = UAR_GET_CODE_DISPLAY(O.TASK_TYPE_CD)
	, O.TASK_ACTIVITY_CD
	, O_TASK_ACTIVITY_DISP = UAR_GET_CODE_DISPLAY(O.TASK_ACTIVITY_CD)
	, O.REFERENCE_TASK_ID
	, O.ALLPOSITIONCHART_IND
	, OT.REFERENCE_TASK_ID
	, OT_POSITION_DISP = UAR_GET_CODE_DISPLAY(OT.POSITION_CD)

FROM
	ORDER_TASK   O
	, ORDER_TASK_POSITION_XREF   OT

PLAN O
WHERE O.DCP_FORMS_REF_ID > 0
AND O.ACTIVE_IND = 1
AND O.TASK_ACTIVITY_CD = 2695
AND O.TASK_TYPE_CD != 2668
JOIN OT WHERE O.REFERENCE_TASK_ID = OT.REFERENCE_TASK_ID

WITH NOCOUNTER, SEPARATOR=" "
